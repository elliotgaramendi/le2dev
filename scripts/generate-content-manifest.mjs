import { readdirSync, writeFileSync } from 'node:fs'
import { join, posix } from 'node:path'

const contentRoot = join(process.cwd(), 'public', 'content', 'desarrollo-frontend')
const outputFile = join(process.cwd(), 'src', 'data', 'contentManifest.ts')

const toTitleFromSlug = (value) =>
  value
    .replace(/^o\d+[-_]?/, '')
    .replace(/^level[-_]?\d+[-_]?/, 'level-')
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .split(' ')
    .map((word) => (word ? `${word.charAt(0).toLocaleUpperCase('es-PE')}${word.slice(1)}` : ''))
    .join(' ')

const normalizeSegment = (segment) =>
  segment
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')

const scanIndexFiles = (directory, found = []) => {
  const entries = readdirSync(directory, { withFileTypes: true })

  for (const entry of entries) {
    const fullPath = join(directory, entry.name)

    if (entry.isDirectory()) {
      scanIndexFiles(fullPath, found)
      continue
    }

    if (entry.isFile() && entry.name === 'index.html') {
      found.push(fullPath)
    }
  }

  return found
}

const indexFiles = scanIndexFiles(contentRoot)
const weekMap = new Map()

for (const filePath of indexFiles.sort()) {
  const relativePath = posix.normalize(filePath.replace(`${process.cwd()}/`, '').replace(/\\/g, '/'))
  const segments = relativePath.split('/')
  const weekSegment = segments[3]

  if (!weekSegment || weekSegment === 'index.html') {
    continue
  }

  const weekSlug = normalizeSegment(weekSegment)
  const weekOrder = Number(weekSegment.match(/^o(\d+)/)?.[1] ?? 0)

  if (!weekMap.has(weekSlug)) {
    weekMap.set(weekSlug, {
      id: weekSegment,
      slug: weekSlug,
      order: weekOrder,
      title: `Semana ${weekOrder}: ${toTitleFromSlug(weekSegment)}`,
      description: `Ruta de practica y proyectos para ${toTitleFromSlug(weekSegment)}.`,
      projects: [],
    })
  }

  if (segments.length <= 5) {
    continue
  }

  const projectRelativePath = segments.slice(4, -1).join('/')
  const projectSlug = projectRelativePath
    .split('/')
    .map((segment) => normalizeSegment(segment))
    .join('--')
  const projectTitle = projectRelativePath
    .split('/')
    .map((segment) => toTitleFromSlug(segment))
    .join(' / ')

  weekMap.get(weekSlug).projects.push({
    id: `${weekSlug}-${projectSlug}`,
    slug: projectSlug,
    title: projectTitle,
    sourcePath: relativePath,
    sourceUrl: encodeURI(`/${relativePath.replace(/^public\//, '')}`),
  })
}

const weeksCatalog = Array.from(weekMap.values())
  .sort((a, b) => a.order - b.order)
  .map((week) => ({
    ...week,
    projects: week.projects.sort((a, b) => a.sourcePath.localeCompare(b.sourcePath)),
  }))

const output = `/* Auto-generated by scripts/generate-content-manifest.mjs */\n` +
  `export const contentManifest = ${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      contentRoot: '/content/desarrollo-frontend',
      weeksCatalog,
    },
    null,
    2,
  )} as const\n`

writeFileSync(outputFile, output)
console.log(`Generated manifest with ${weeksCatalog.length} weeks at ${outputFile}`)
